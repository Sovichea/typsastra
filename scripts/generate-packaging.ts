/**
 * Generate Chocolatey, Scoop, and AUR packaging metadata for a published
 * Typsastra release.
 *
 * Usage:
 *   bun scripts/generate-packaging.ts <version> [--dry-run]
 *
 * Asset URLs and SHA-256 digests come from the GitHub release. Publish the
 * release first; do not copy hashes from an older version.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const REPOSITORY = "Sovichea/typsastra";
const HOMEPAGE = `https://github.com/${REPOSITORY}`;
const DOCS_URL = "https://docs.typsastra.com/";
const PACKAGE_ID = "typsastra";
const AUR_PACKAGE = "typsastra-bin";
const DESCRIPTION =
  "Typst editor with live preview, autocomplete, outline, diagnostics, and project navigation.";
const AUR_DESCRIPTION = DESCRIPTION.replace(/\.$/u, "");
const SUMMARY = "Typst editor for research and long-form multilingual writing.";
const TAGS = ["typst", "editor", "typesetting", "latex", "preview", "tinymist"];
const ROOT = resolve(import.meta.dir, "..");
const PACKAGING_ROOT = join(ROOT, "packaging");

export interface ReleaseAsset {
  name: string;
  url: string;
  digest: string;
}

export interface Release {
  version: string;
  tag: string;
  assets: Map<string, ReleaseAsset>;
}

export interface GeneratedFile {
  path: string;
  contents: string;
}

function fail(message: string): never {
  throw new Error(message);
}

function xmlEscape(value: string): string {
  return value
    .replace(/&/gu, "&amp;")
    .replace(/</gu, "&lt;")
    .replace(/>/gu, "&gt;")
    .replace(/"/gu, "&quot;");
}

function msiName(version: string, architecture: "x64" | "arm64"): string {
  return `Typsastra_${version}_${architecture}_en-US.msi`;
}

function debName(version: string, architecture: "amd64" | "arm64"): string {
  return `Typsastra_${version}_${architecture}.deb`;
}

function releaseAsset(release: Release, name: string): ReleaseAsset {
  const asset = release.assets.get(name);
  if (!asset) fail(`Release ${release.tag} is missing ${name}.`);
  return asset;
}

function assetSha256(asset: ReleaseAsset): string {
  const match = /^sha256:([0-9a-f]{64})$/u.exec(asset.digest);
  if (!match) {
    fail(
      `Release asset ${asset.name} has no SHA-256 digest (${asset.digest || "<missing>"}). ` +
        "Re-upload the asset so GitHub reports a digest, or extend this generator to hash a local download.",
    );
  }
  return match[1];
}

export function renderChocolateyNuspec(release: Release): string {
  // Validate that both installers exist even though the nuspec only links to
  // the release; the install script carries the architecture-specific URLs.
  releaseAsset(release, msiName(release.version, "x64"));
  releaseAsset(release, msiName(release.version, "arm64"));
  return `<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://schemas.microsoft.com/packaging/2015/06/nuspec.xsd">
  <metadata>
    <id>${PACKAGE_ID}</id>
    <version>${release.version}</version>
    <title>Typsastra</title>
    <authors>Typsastra</authors>
    <owners>Typsastra</owners>
    <projectUrl>${HOMEPAGE}</projectUrl>
    <projectSourceUrl>${HOMEPAGE}</projectSourceUrl>
    <packageSourceUrl>${HOMEPAGE}/tree/${release.tag}/packaging/chocolatey</packageSourceUrl>
    <docsUrl>${DOCS_URL}</docsUrl>
    <bugTrackerUrl>${HOMEPAGE}/issues</bugTrackerUrl>
    <licenseUrl>${HOMEPAGE}/blob/${release.tag}/LICENSE</licenseUrl>
    <requireLicenseAcceptance>false</requireLicenseAcceptance>
    <description>${xmlEscape(DESCRIPTION)}</description>
    <summary>${xmlEscape(SUMMARY)}</summary>
    <releaseNotes>See ${HOMEPAGE}/releases/tag/${release.tag}</releaseNotes>
    <copyright>Copyright (c) Typsastra contributors</copyright>
    <tags>${TAGS.join(" ")}</tags>
    <iconUrl>https://raw.githubusercontent.com/${REPOSITORY}/${release.tag}/src-tauri/icons/128x128.png</iconUrl>
  </metadata>
  <files>
    <file src="tools\\**" target="tools" />
  </files>
</package>
`;
}

export function renderChocolateyInstall(release: Release): string {
  const x64 = releaseAsset(release, msiName(release.version, "x64"));
  const arm64 = releaseAsset(release, msiName(release.version, "arm64"));
  return `# Generated by \`bun run generate:packaging ${release.version}\`.
# Downloads the official per-machine MSI from the GitHub release.
$ErrorActionPreference = 'Stop'

if (-not [Environment]::Is64BitOperatingSystem) {
  throw 'Typsastra requires a 64-bit version of Windows.'
}

$isArm64 = $env:PROCESSOR_ARCHITECTURE -eq 'ARM64' -or $env:PROCESSOR_ARCHITEW6432 -eq 'ARM64'
$url = if ($isArm64) { '${arm64.url}' } else { '${x64.url}' }
$checksum = if ($isArm64) { '${assetSha256(arm64)}' } else { '${assetSha256(x64)}' }

$packageArgs = @{
  packageName    = $env:ChocolateyPackageName
  fileType       = 'msi'
  url64bit       = $url
  checksum64     = $checksum
  checksumType64 = 'sha256'
  silentArgs     = '/quiet /norestart'
  validExitCodes = @(0, 3010, 1641)
  softwareName   = 'Typsastra'
}

Install-ChocolateyPackage @packageArgs
`;
}

export function renderChocolateyUninstall(): string {
  return `# Generated by the Typsastra packaging generator.
$ErrorActionPreference = 'Stop'

$keys = @(Get-UninstallRegistryKey -SoftwareName 'Typsastra')
if ($keys.Count -eq 0) {
  Write-Warning 'Typsastra is not installed.'
  return
}

foreach ($key in $keys) {
  $productCode = $key.PSChildName
  if ($productCode -notmatch '^\\{[0-9A-Fa-f-]{36}\\}$') {
    continue
  }

  $exitCode = (Start-Process -FilePath 'msiexec.exe' \`
      -ArgumentList @('/x', $productCode, '/qn', '/norestart') \`
      -Wait -PassThru).ExitCode
  if ($exitCode -notin @(0, 3010, 1641)) {
    throw "Uninstalling Typsastra failed with exit code $exitCode."
  }
}
`;
}

export function renderChocolateyVerification(release: Release): string {
  const x64 = releaseAsset(release, msiName(release.version, "x64"));
  const arm64 = releaseAsset(release, msiName(release.version, "arm64"));
  return `VERIFICATION
Verification is intended to assist the Chocolatey moderators and community
in verifying that this package's contents are trustworthy.

The installers are downloaded from the official Typsastra GitHub release:
${HOMEPAGE}/releases/tag/${release.tag}

x64
  URL:    ${x64.url}
  SHA256: ${assetSha256(x64)}

arm64
  URL:    ${arm64.url}
  SHA256: ${assetSha256(arm64)}

The package installs the per-machine MSI with the standard Windows Installer
silent switches. Windows installers are not code signed.
`;
}

export function renderScoopManifest(release: Release): string {
  const x64 = releaseAsset(release, msiName(release.version, "x64"));
  const arm64 = releaseAsset(release, msiName(release.version, "arm64"));
  const manifest = {
    $schema: "https://raw.githubusercontent.com/ScoopInstaller/Schemas/master/installer.json",
    version: release.version,
    description: DESCRIPTION,
    homepage: HOMEPAGE,
    notes:
      "Requires the Microsoft Edge WebView2 Runtime, which is included with Windows 11 and most Windows 10 installations.",
    license: {
      identifier: "MIT",
      url: `${HOMEPAGE}/blob/${release.tag}/LICENSE`,
    },
    architecture: {
      "64bit": {
        url: x64.url,
        hash: assetSha256(x64),
      },
      arm64: {
        url: arm64.url,
        hash: assetSha256(arm64),
      },
    },
    installer: {
      script: [
        `Expand-MsiArchive "$dir\\$fname" "$dir" -ExtractDir 'PFiles\\Typsastra'`,
        `Remove-Item "$dir\\$fname" -Force`,
      ],
    },
    bin: "typsastra.exe",
    shortcuts: [["typsastra.exe", "Typsastra"]],
    checkver: {
      github: HOMEPAGE,
    },
    autoupdate: {
      architecture: {
        "64bit": {
          url: `${HOMEPAGE}/releases/download/v$version/Typsastra_$version_x64_en-US.msi`,
          hash: {
            url: `https://api.github.com/repos/${REPOSITORY}/releases/tags/v$version`,
            jsonpath: "$.assets[?(@.name == 'Typsastra_$version_x64_en-US.msi')].digest",
          },
        },
        arm64: {
          url: `${HOMEPAGE}/releases/download/v$version/Typsastra_$version_arm64_en-US.msi`,
          hash: {
            url: `https://api.github.com/repos/${REPOSITORY}/releases/tags/v$version`,
            jsonpath: "$.assets[?(@.name == 'Typsastra_$version_arm64_en-US.msi')].digest",
          },
        },
      },
    },
  };
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

export function renderAurPkgbuild(release: Release): string {
  const x64 = releaseAsset(release, debName(release.version, "amd64"));
  const arm64 = releaseAsset(release, debName(release.version, "arm64"));
  return `# Maintainer: Typsastra contributors <${HOMEPAGE}/issues>
pkgname=${AUR_PACKAGE}
pkgver=${release.version}
pkgrel=1
pkgdesc="${AUR_DESCRIPTION}"
arch=('x86_64' 'aarch64')
url="${HOMEPAGE}"
license=('MIT')
depends=('gtk3' 'webkit2gtk-4.1' 'xdg-utils')
provides=('typsastra')
conflicts=('typsastra')
options=('!strip' '!debug')
source_x86_64=('${x64.url}')
source_aarch64=('${arm64.url}')
noextract=("Typsastra_${release.version}_amd64.deb" "Typsastra_${release.version}_arm64.deb")
sha256sums_x86_64=('${assetSha256(x64)}')
sha256sums_aarch64=('${assetSha256(arm64)}')

package() {
  local deb
  case "$CARCH" in
    x86_64) deb="Typsastra_${release.version}_amd64.deb" ;;
    aarch64) deb="Typsastra_${release.version}_arm64.deb" ;;
    *) error "Unsupported architecture: $CARCH" ;;
  esac

  # The Debian package is a thin wrapper around the same Tauri bundle. Extract
  # its data archive instead of depending on dpkg on Arch Linux.
  bsdtar -xOf "$srcdir/$deb" data.tar.* | bsdtar -xf - -C "$pkgdir"
}
`;
}

export function renderAurSrcinfo(release: Release): string {
  const x64 = releaseAsset(release, debName(release.version, "amd64"));
  const arm64 = releaseAsset(release, debName(release.version, "arm64"));
  return `pkgbase = ${AUR_PACKAGE}
\tpkgdesc = ${AUR_DESCRIPTION}
\tpkgver = ${release.version}
\tpkgrel = 1
\turl = ${HOMEPAGE}
\tarch = x86_64
\tarch = aarch64
\tlicense = MIT
\tdepends = gtk3
\tdepends = webkit2gtk-4.1
\tdepends = xdg-utils
\tprovides = typsastra
\tconflicts = typsastra
\toptions = !strip
\toptions = !debug
\tsource_x86_64 = ${x64.url}
\tsource_aarch64 = ${arm64.url}
\tnoextract = Typsastra_${release.version}_amd64.deb
\tnoextract = Typsastra_${release.version}_arm64.deb
\tsha256sums_x86_64 = ${assetSha256(x64)}
\tsha256sums_aarch64 = ${assetSha256(arm64)}
pkgname = ${AUR_PACKAGE}
`;
}

export function renderPackagingFiles(release: Release): GeneratedFile[] {
  return [
    {
      path: join(PACKAGING_ROOT, "chocolatey", `${PACKAGE_ID}.nuspec`),
      contents: renderChocolateyNuspec(release),
    },
    {
      path: join(PACKAGING_ROOT, "chocolatey", "tools", "chocolateyinstall.ps1"),
      contents: renderChocolateyInstall(release),
    },
    {
      path: join(PACKAGING_ROOT, "chocolatey", "tools", "chocolateyuninstall.ps1"),
      contents: renderChocolateyUninstall(),
    },
    {
      path: join(PACKAGING_ROOT, "chocolatey", "tools", "VERIFICATION.txt"),
      contents: renderChocolateyVerification(release),
    },
    {
      path: join(PACKAGING_ROOT, "scoop", `${PACKAGE_ID}.json`),
      contents: renderScoopManifest(release),
    },
    {
      path: join(PACKAGING_ROOT, "aur", "PKGBUILD"),
      contents: renderAurPkgbuild(release),
    },
    {
      path: join(PACKAGING_ROOT, "aur", ".SRCINFO"),
      contents: renderAurSrcinfo(release),
    },
  ];
}

function parseArguments(argv: string[]): { version: string; dryRun: boolean } {
  const positional: string[] = [];
  let dryRun = false;
  for (const argument of argv) {
    if (argument === "--dry-run") dryRun = true;
    else if (argument.startsWith("--")) fail(`Unknown option ${argument}.`);
    else positional.push(argument);
  }
  if (positional.length !== 1) fail("Expected exactly one version, for example 0.10.0.");
  const version = positional[0].replace(/^v/u, "");
  if (!/^\d+\.\d+\.\d+$/u.test(version)) fail(`Invalid version ${JSON.stringify(version)}.`);
  return { version, dryRun };
}

function readRelease(version: string): Release {
  if (!Bun.which("gh")) {
    fail("gh was not found. Install the GitHub CLI to read published release assets.");
  }
  const tag = `v${version}`;
  const result = Bun.spawnSync({
    cmd: ["gh", "release", "view", tag, "--repo", REPOSITORY, "--json", "tagName,assets"],
    stdout: "pipe",
    stderr: "pipe",
    windowsHide: true,
  });
  if (result.exitCode !== 0) {
    fail(
      `Could not read release ${tag}. Publish the release first. ` +
        new TextDecoder().decode(result.stderr).trim(),
    );
  }
  const payload = JSON.parse(new TextDecoder().decode(result.stdout).trim()) as {
    tagName: string;
    assets: { name: string; url: string; digest: string }[];
  };
  if (payload.tagName !== tag) fail(`Expected release ${tag} but gh returned ${payload.tagName}.`);
  const assets = new Map(payload.assets.map(asset => [asset.name, asset]));
  return { version, tag, assets };
}

async function main(): Promise<void> {
  const options = parseArguments(process.argv.slice(2));
  const packageVersion = (JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as {
    version: string;
  }).version;
  if (packageVersion !== options.version) {
    console.warn(
      `warning: package.json is at ${packageVersion} but generating packaging for ${options.version}. ` +
        "Bump the version before tagging a release.",
    );
  }

  const release = readRelease(options.version);
  const files = renderPackagingFiles(release);

  if (options.dryRun) {
    console.log("Would write:");
    for (const file of files) {
      const existing = existsSync(file.path);
      const status = !existing
        ? "new"
        : readFileSync(file.path, "utf8") === file.contents
          ? "unchanged"
          : "CHANGED";
      console.log(`  ${status.padEnd(9)} ${relative(ROOT, file.path)}`);
    }
    console.log("\n--dry-run: nothing written.");
    return;
  }

  for (const file of files) {
    mkdirSync(dirname(file.path), { recursive: true });
    writeFileSync(file.path, file.contents, "utf8");
  }

  console.log(`\n${options.version}:`);
  for (const [architecture, name] of [
    ["x64", msiName(options.version, "x64")],
    ["arm64", msiName(options.version, "arm64")],
    ["amd64 deb", debName(options.version, "amd64")],
    ["arm64 deb", debName(options.version, "arm64")],
  ] as const) {
    const asset = releaseAsset(release, name);
    console.log(`  ${architecture.padEnd(10)} ${assetSha256(asset)}  ${asset.url}`);
  }
  console.log(`  wrote ${files.length} files under ${relative(ROOT, PACKAGING_ROOT)}/`);
}

if (import.meta.main) {
  try {
    await main();
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
